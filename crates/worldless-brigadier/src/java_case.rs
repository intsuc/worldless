const IGNORE_CATEGORY: u8 = u8::MAX;
const START_STATE: usize = 1;
const STOP_STATE: usize = 0;
const WORD_CATEGORY_COUNT: usize = 22;

pub(crate) fn java_root_lowercase(input: &[u16]) -> Vec<u16> {
    let mut result = Vec::with_capacity(input.len());
    let mut cursor = 0;
    while cursor < input.len() {
        let (code_point, width) = code_point_at(input, cursor);
        if code_point == 0x03a3 && WordBreakIterator::new(input).is_final_cased(cursor) {
            result.push(0x03c2);
        } else if java25_preserves_case(code_point) || char::from_u32(code_point).is_none() {
            result.extend_from_slice(&input[cursor..cursor + width]);
        } else {
            let character = char::from_u32(code_point).expect("checked above");
            for lowercase in character.to_lowercase() {
                let mut units = [0; 2];
                result.extend_from_slice(lowercase.encode_utf16(&mut units));
            }
        }
        cursor += width;
    }
    result
}

pub(crate) fn java25_preserves_case(code_point: u32) -> bool {
    matches!(
        code_point,
        0xa7ce..=0xa7cf | 0xa7d2..=0xa7d5 | 0x16ea0..=0x16ed3
    )
}

struct WordBreakIterator<'a> {
    input: &'a [u16],
    index: usize,
    cached_break: isize,
}

impl<'a> WordBreakIterator<'a> {
    fn new(input: &'a [u16]) -> Self {
        Self {
            input,
            index: 0,
            cached_break: -1,
        }
    }

    fn is_final_cased(&mut self, index: usize) -> bool {
        let mut cursor = index;
        while cursor > 0 && !self.is_boundary(cursor) {
            let (code_point, width) = code_point_before(self.input, cursor);
            if is_cased(code_point) {
                cursor = index + code_point_at(self.input, index).1;
                while cursor < self.input.len() && !self.is_boundary(cursor) {
                    let (code_point, width) = code_point_at(self.input, cursor);
                    if is_cased(code_point) {
                        return false;
                    }
                    cursor += width;
                }
                return true;
            }
            cursor -= width;
        }
        false
    }

    fn is_boundary(&mut self, offset: usize) -> bool {
        if offset == 0 {
            true
        } else {
            self.following(offset - 1) == offset as isize
        }
    }

    fn following(&mut self, offset: usize) -> isize {
        self.index = offset;
        if offset == 0 {
            let result = self.handle_next();
            self.cached_break = result;
            return result;
        }

        let mut result = self.cached_break;
        if result >= offset as isize || result <= -1 {
            result = self.handle_previous() as isize;
        } else {
            self.index = result as usize;
        }
        while result != -1 && result <= offset as isize {
            result = self.handle_next();
        }
        self.cached_break = result;
        result
    }

    fn handle_next(&mut self) -> isize {
        if self.index == self.input.len() {
            return -1;
        }

        let mut result = self.next_index();
        let mut state = START_STATE;
        let mut current = self.current();
        while let Some(code_point) = current.filter(|_| state != STOP_STATE) {
            let category = word_category(code_point);
            if category != IGNORE_CATEGORY {
                state = usize::from(
                    WORD_FORWARD_STATES[state * WORD_CATEGORY_COUNT + usize::from(category)],
                );
            }
            if is_end_state(state) {
                result = self.next_index();
            }
            current = self.next_code_point();
        }
        self.index = result;
        result as isize
    }

    fn handle_previous(&mut self) -> usize {
        let mut state = START_STATE;
        let mut category = 0;
        let mut last_category = 0;
        let mut current = self.current();
        while let Some(code_point) = current.filter(|_| state != STOP_STATE) {
            last_category = category;
            category = word_category(code_point);
            if category != IGNORE_CATEGORY {
                state = usize::from(
                    WORD_BACKWARD_STATES[state * WORD_CATEGORY_COUNT + usize::from(category)],
                );
            }
            current = self.previous_code_point();
        }
        if current.is_some() {
            self.next_code_point();
            if last_category != IGNORE_CATEGORY {
                self.next_code_point();
            }
        }
        self.index
    }

    fn current(&self) -> Option<u32> {
        if self.index >= self.input.len() {
            return None;
        }
        let code_point = code_point_at(self.input, self.index).0;
        (code_point != 0xffff).then_some(code_point)
    }

    fn next_index(&self) -> usize {
        if self.index >= self.input.len() {
            self.input.len()
        } else {
            (self.index + code_point_at(self.input, self.index).1).min(self.input.len())
        }
    }

    fn next_code_point(&mut self) -> Option<u32> {
        if self.index == self.input.len() {
            return None;
        }
        let next = self.next_index();
        if next >= self.input.len() {
            return None;
        }
        self.index = next;
        self.current()
    }

    fn previous_code_point(&mut self) -> Option<u32> {
        if self.index == 0 {
            return None;
        }
        self.index -= 1;
        let second = self.input[self.index];
        let code_point = if (0xdc00..=0xdfff).contains(&second) && self.index > 0 {
            self.index -= 1;
            let first = self.input[self.index];
            if (0xd800..=0xdbff).contains(&first) {
                0x10000 + ((u32::from(first) - 0xd800) << 10) + (u32::from(second) - 0xdc00)
            } else {
                self.index += 1;
                u32::from(second)
            }
        } else {
            u32::from(second)
        };
        (code_point != 0xffff).then_some(code_point)
    }
}

fn code_point_at(input: &[u16], index: usize) -> (u32, usize) {
    let first = input[index];
    if (0xd800..=0xdbff).contains(&first)
        && input
            .get(index + 1)
            .is_some_and(|second| (0xdc00..=0xdfff).contains(second))
    {
        let second = input[index + 1];
        (
            0x10000 + ((u32::from(first) - 0xd800) << 10) + (u32::from(second) - 0xdc00),
            2,
        )
    } else {
        (u32::from(first), 1)
    }
}

fn code_point_before(input: &[u16], index: usize) -> (u32, usize) {
    let second = input[index - 1];
    if (0xdc00..=0xdfff).contains(&second)
        && index >= 2
        && (0xd800..=0xdbff).contains(&input[index - 2])
    {
        let first = input[index - 2];
        (
            0x10000 + ((u32::from(first) - 0xd800) << 10) + (u32::from(second) - 0xdc00),
            2,
        )
    } else {
        (u32::from(second), 1)
    }
}

fn word_category(code_point: u32) -> u8 {
    let index = WORD_CATEGORY_TRANSITIONS.partition_point(|entry| entry >> 8 <= code_point);
    WORD_CATEGORY_TRANSITIONS[index - 1] as u8
}

fn is_end_state(state: usize) -> bool {
    WORD_END_STATES & (1 << state) != 0
}

fn is_cased(code_point: u32) -> bool {
    let index = CASED_RANGES.partition_point(|range| range.0 <= code_point);
    index > 0 && code_point <= CASED_RANGES[index - 1].1
}

