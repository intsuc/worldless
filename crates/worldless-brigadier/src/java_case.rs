#[cfg(test)]
mod tests {
    use super::*;

    fn lower(input: &str) -> String {
        String::from_utf16(&java_root_lowercase(
            &input.encode_utf16().collect::<Vec<_>>(),
        ))
        .unwrap()
    }

    #[test]
    fn root_special_casing() {
        assert_eq!(lower("\u{130}"), "i\u{307}");
        assert_eq!(lower("\u{a7ce}A"), "\u{a7ce}a");
    }

    #[test]
    fn final_sigma_uses_java_word_boundaries() {
        assert_eq!(lower("Σ"), "σ");
        assert_eq!(lower("ΟΣ"), "ος");
        assert_eq!(lower("ΟΣΑ"), "οσα");
        assert_eq!(lower("A\0Σ"), "a\0σ");
        assert_eq!(lower("A:Σ"), "a:σ");
        assert_eq!(lower("AΣ\u{301}"), "aς\u{301}");
        assert_eq!(lower("AΣ\u{345}"), "aσ\u{345}");
        assert_eq!(lower("AΣ\u{2b0}"), "aσ\u{2b0}");
        assert_eq!(lower("AΣ\u{1f130}"), "aς\u{1f130}");
        assert_eq!(lower("𐐀Σ"), "𐐨ς");
        assert_eq!(lower("A𐐀Σ"), "a𐐨σ");
        assert_eq!(lower("𐐀AΣ"), "𐐨aς");
        assert_eq!(lower("AΣ𐐀"), "aσ𐐨");
        assert_eq!(lower("A𐐀\u{301}Σ"), "a𐐨\u{301}σ");
        assert_eq!(
            lower("Σ\u{a76a9}\u{61a2f}Σ\u{23611}Σ"),
            "σ\u{a76a9}\u{61a2f}σ\u{23611}σ"
        );
    }

    #[test]
    fn unpaired_surrogates_are_preserved() {
        assert_eq!(
            java_root_lowercase(&[0xd800, b'A' as u16]),
            [0xd800, b'a' as u16]
        );
        assert_eq!(
            java_root_lowercase(&[0xdc00, b'A' as u16]),
            [0xdc00, b'a' as u16]
        );
    }
}
